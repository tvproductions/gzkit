"""Render registered neutral role bodies into native Codex and Claude agent files.

Codex: only captured legacy bodies and explicitly managed files are replaced. Native
metadata remains byte-for-byte intact; unknown and customized roles are owned by the
user. Claude: every registered role's body is generated from canon and its frontmatter
kept, so a hand edit to a Claude copy is drift (GHI #1328; operator, 2026-11-14:
"A: Generate from canon"). Writes use the shared capture sink for read-only sync planning.
"""

import hashlib
import json
import re
import tomllib
from pathlib import Path

from gzkit.surface_write import ensure_dir, write_text_if_changed

MARKER = "# Generated by gzkit from .gzkit/agents; role body managed, metadata preserved."
_BODY_KEY = re.compile(
    r"(?m)^[ \t]*(?:developer_instructions|\"developer_instructions\""
    r"|'developer_instructions')[ \t]*="
)


# A TypeError too: raised when an isinstance check fails (TRY004); ValueError keeps its handlers.
class NonStringDeveloperInstructionsError(ValueError, TypeError):
    """A Codex role's ``developer_instructions`` value is not a string."""

    def __init__(self, name: str | None = None) -> None:
        """Build the refusal message from ``name``."""
        self.name = name
        message = "Codex role developer_instructions must be a string"
        super().__init__(message if name is None else f"{message}: {name}")


class UnsafeRoleBodyReplacementError(ValueError):
    """No line span replaces ``developer_instructions`` while preserving every other value."""

    def __init__(self) -> None:
        """Build the fixed refusal message."""
        super().__init__("Cannot safely replace Codex role developer_instructions")


class InvalidRoleRegistrationError(ValueError):
    """A registered Codex role has an invalid name or non-mapping metadata."""

    def __init__(self) -> None:
        """Build the fixed refusal message."""
        super().__init__("Invalid canonical Codex role registration")


# A TypeError too: raised when an isinstance check fails (TRY004); ValueError keeps its handlers.
class InvalidRoleMetadataError(ValueError, TypeError):
    """A registered Codex role lacks a string description or legacy body digest."""

    def __init__(self, name: str) -> None:
        """Build the refusal message from ``name``."""
        self.name = name
        super().__init__(f"Invalid canonical Codex role metadata: {name}")


class EmptyCanonicalRoleError(ValueError):
    """A registered Codex role's canonical body is empty."""

    def __init__(self, name: str) -> None:
        """Build the refusal message from ``name``."""
        self.name = name
        super().__init__(f"Empty canonical Codex role: {name}")


class UnsupportedRoleRegistryError(ValueError):
    """The Codex role registry is not a version-1 mapping."""

    def __init__(self) -> None:
        """Build the fixed refusal message."""
        super().__init__("Unsupported canonical Codex role registry")


# A TypeError too: raised when an isinstance check fails (TRY004); ValueError keeps its handlers.
class MalformedClaudeRoleError(ValueError):
    """A Claude role file opens a frontmatter block it never closes."""

    def __init__(self, name: str) -> None:
        """Build the refusal message from ``name``."""
        self.name = name
        super().__init__(f"Claude role frontmatter is not closed: {name}")


class MissingRolesMappingError(ValueError, TypeError):
    """The Codex role registry carries no ``roles`` mapping."""

    def __init__(self) -> None:
        """Build the fixed refusal message."""
        super().__init__("Canonical Codex role registry requires a roles mapping")


def render_codex_role(source: str, body: str) -> str:
    """Replace one root string while proving every other TOML value survives.

    Try complete line spans instead of interpreting TOML string escapes. Parsing
    the candidate and comparing the whole document also rejects apparent keys
    embedded inside another multiline string or a nested table.

    Returns:
        The source with the `developer_instructions` value replaced by the JSON-quoted body and
        every other value unchanged, prefixed by the marker line when it does not already open with
        it.

    Raises:
        NonStringDeveloperInstructionsError: when `developer_instructions` is not a string.
        UnsafeRoleBodyReplacementError: when no replacement preserves every other value.

    """
    original = tomllib.loads(source)
    if not isinstance(original.get("developer_instructions"), str):
        raise NonStringDeveloperInstructionsError
    expected = {**original, "developer_instructions": body}
    for match in _BODY_KEY.finditer(source):
        ends = [m.end() for m in re.finditer("\n", source[match.end() :])]
        for end in [*(match.end() + offset for offset in ends), len(source)]:
            candidate = (
                source[: match.start()]
                + "developer_instructions = "
                + json.dumps(body, ensure_ascii=False)
                + "\n"
                + source[end:]
            )
            try:
                parsed = tomllib.loads(candidate)
            except tomllib.TOMLDecodeError:
                continue
            if parsed == expected:
                return (
                    candidate if candidate.startswith(MARKER + "\n") else MARKER + "\n" + candidate
                )
    raise UnsafeRoleBodyReplacementError


def _role_output(root: Path, name: str, metadata: object) -> tuple[Path, str] | None:
    """Plan one registered role, leaving customized native bodies untouched."""
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name) or not isinstance(metadata, dict):
        raise InvalidRoleRegistrationError
    description = metadata.get("description")
    digest = metadata.get("legacy_codex_body_sha256")
    if not isinstance(description, str) or not isinstance(digest, str):
        raise InvalidRoleMetadataError(name)
    body = (root / ".gzkit/agents" / f"{name}.md").read_text(encoding="utf-8").strip()
    if not body:
        raise EmptyCanonicalRoleError(name)
    destination = root / ".codex/agents" / f"{name}.toml"
    if not destination.exists():
        source = f"name = {json.dumps(name)}\ndescription = {json.dumps(description)}\n"
        source += 'developer_instructions = ""\n'
    else:
        source = destination.read_text(encoding="utf-8")
        current = tomllib.loads(source).get("developer_instructions")
        if not isinstance(current, str):
            raise NonStringDeveloperInstructionsError(name)
        legacy = hashlib.sha256(current.strip().encode("utf-8")).hexdigest() == digest
        if not (source.startswith(MARKER + "\n") or legacy or current.strip() == body):
            return None
    return destination, render_codex_role(source, body)


def sync_codex_roles(project_root: Path) -> list[str]:
    """Sync registered roles; return all managed project-relative paths.

    No registry means no ownership and no writes. Preflight every role before
    applying any writes so an invalid registry, body, or native TOML fails cleanly.
    The caller decides whether Codex delivery is enabled for this project.

    Returns:
        Project-relative POSIX paths of every role file the registry manages, in role-name order;
        empty when no registry exists. An unsupported registry raises from
        :func:`_registered_roles`.

    """
    roles = _registered_roles(project_root)
    outputs = [
        _role_output(project_root, name, metadata) for name, metadata in sorted(roles.items())
    ]
    managed = []
    for output in outputs:
        if output is not None:
            path, content = output
            write_text_if_changed(path, content)
            managed.append(path.relative_to(project_root).as_posix())
    return managed


def _registered_roles(project_root: Path) -> dict[str, object]:
    """Return the role registry's ``roles`` mapping; empty when there is no registry.

    Returns:
        Role name mapped to its registered metadata.

    Raises:
        UnsupportedRoleRegistryError: when the registry is not a version-1 mapping.
        MissingRolesMappingError: when the registry carries no `roles` mapping.

    """
    registry_path = project_root / ".gzkit/agents/roles.json"
    if not registry_path.exists():
        return {}
    registry = json.loads(registry_path.read_text(encoding="utf-8"))
    if not isinstance(registry, dict) or registry.get("version") != 1:
        raise UnsupportedRoleRegistryError
    roles = registry.get("roles")
    if not isinstance(roles, dict):
        raise MissingRolesMappingError
    return roles


def render_claude_role(source: str | None, name: str, description: str, body: str) -> str:
    """Return a Claude role file whose body is *body*, its frontmatter kept.

    An existing file's frontmatter (``tools``, ``model``, ``maxTurns`` and the rest)
    stays byte-for-byte; a missing file gets only ``name`` and ``description``.

    Returns:
        The frontmatter block, a blank line, then the body and a final newline.

    Raises:
        MalformedClaudeRoleError: when *source* opens a frontmatter block it never closes.

    """
    if source is not None and source.startswith("---\n"):
        end = source.find("\n---\n", 3)
        if end == -1:
            raise MalformedClaudeRoleError(name)
        frontmatter = source[: end + len("\n---\n")]
    else:
        frontmatter = f"---\nname: {name}\ndescription: {json.dumps(description)}\n---\n"
    return f"{frontmatter}\n{body}\n"


def sync_claude_roles(project_root: Path) -> list[str]:
    """Generate each registered role's Claude file from its canonical body.

    Returns:
        Project-relative POSIX paths of every Claude role file the registry manages, in
        role-name order; empty when no registry exists.

    Raises:
        InvalidRoleRegistrationError: when a role name is not kebab-case or its metadata is not
            a mapping.
        InvalidRoleMetadataError: when a role carries no string description.
        EmptyCanonicalRoleError: when a role's canonical body is empty.

    """
    planned = []
    for name, metadata in sorted(_registered_roles(project_root).items()):
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name) or not isinstance(metadata, dict):
            raise InvalidRoleRegistrationError
        description = metadata.get("description")
        if not isinstance(description, str):
            raise InvalidRoleMetadataError(name)
        body = (project_root / ".gzkit/agents" / f"{name}.md").read_text(encoding="utf-8").strip()
        if not body:
            raise EmptyCanonicalRoleError(name)
        destination = project_root / ".claude/agents" / f"{name}.md"
        source = destination.read_text(encoding="utf-8") if destination.exists() else None
        planned.append((destination, render_claude_role(source, name, description, body)))
    managed = []
    for destination, content in planned:
        ensure_dir(destination.parent)
        write_text_if_changed(destination, content)
        managed.append(destination.relative_to(project_root).as_posix())
    return managed
