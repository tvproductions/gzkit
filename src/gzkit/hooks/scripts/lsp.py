"""Prefer-LSP Claude hook script generator."""

from textwrap import dedent


def _prefer_lsp_script() -> str:
    """Return the prefer-LSP PreToolUse hook script.

    PreToolUse hook on Grep, Bash and PowerShell. The first text search for a
    bare Python symbol over Python files in a session is denied with a pointer
    to the ty-backed LSP tool; repeating the same search passes. Delivered
    through the generator so the hook reaches every adopter that receives the
    CLAUDE.md line it enforces (GHI #1278).

    Returns:
        The hook script source.

    """
    return dedent(
        '''\
            #!/usr/bin/env python3
            """Prefer-LSP Hook.

            PreToolUse hook on Grep, Bash and PowerShell. Denies a text search for a
            bare Python symbol over Python files the first time it is tried in a session
            and points at the LSP tool (backed by ty) instead. Repeating the same search
            in the same session lets it through, so the hook nudges and never traps.

            Standard library only. Generated by gzkit and run through `uv run python` like
            the other generated hooks, so it ships to every adopter that receives the
            CLAUDE.md line it enforces (GHI #1278).

            Exit codes:
              0 - Always. A denial is a PreToolUse JSON decision on stdout.
            """

            import contextlib
            import json
            import re
            import shlex
            import sys
            import tempfile
            from pathlib import Path

            SYMBOL_RE = re.compile(r"^(def |class )?[A-Za-z_][A-Za-z0-9_.]{3,}$")
            SEARCH_TOOLS = {"grep", "egrep", "rg", "ugrep"}
            SEGMENT_SPLIT_RE = re.compile(r"\\|\\||&&|[|;\\n]")

            # Options whose value is the next token. A file-filter option also counts
            # as a filter on the search; a regexp option carries the pattern.
            FILTER_OPTS = {"--include", "-g", "--glob", "-t", "--type", "--iglob", "-T", "--type-not"}
            REGEXP_OPTS = {"-e", "--regexp"}
            VALUE_OPTS = (
                FILTER_OPTS
                | REGEXP_OPTS
                | {
                    "-f",
                    "--file",
                    "-m",
                    "--max-count",
                    "-A",
                    "-B",
                    "-C",
                    "--after-context",
                    "--before-context",
                    "--context",
                    "--exclude",
                    "--exclude-dir",
                    "-j",
                    "--threads",
                    "-M",
                    "--max-columns",
                }
            )


            def strip_dressing(pattern: str) -> str:
                """Remove regex word-boundary, whitespace, paren and anchor dressing.

                Returns:
                    The pattern without the dressing.
                """
                pattern = re.sub(r"\\\\s[+*?]?", " ", pattern)
                pattern = pattern.replace(r"\\b", "").replace(r"\\(", "")
                return pattern.strip("^$").strip()


            def symbol_of(pattern: str | None) -> str | None:
                """Name the bare symbol a search pattern looks for.

                Returns:
                    The symbol without any def/class prefix, or None when it is not one.
                """
                if not pattern:
                    return None
                cleaned = strip_dressing(pattern)
                if not SYMBOL_RE.match(cleaned):
                    return None
                return cleaned.split(" ", 1)[-1]


            def names_py(value: str) -> bool:
                """Test whether a filter value names Python files.

                Returns:
                    True when the value names py or pyi.
                """
                return re.search(r"(^|[^A-Za-z])pyi?($|[^A-Za-z])", value) is not None


            def file_filter(value: str) -> str | None:
                """Treat a path that names files by suffix as a filter.

                Returns:
                    The path when it has a suffix, otherwise None.
                """
                return value if Path(value.rstrip("/")).suffix else None


            def covers_python(filters: list[str]) -> bool:
                """Test whether a search covers Python files.

                Returns:
                    True when there is no filter or a filter names py.
                """
                return not filters or any(names_py(f) for f in filters)


            def from_grep_tool(tool_input: dict) -> tuple[str | None, list[str]]:
                """Read a Grep tool call.

                Returns:
                    The pattern and the file filters.
                """
                filters = [str(tool_input[k]) for k in ("glob", "type") if tool_input.get(k)]
                path = tool_input.get("path")
                if path and file_filter(str(path)):
                    filters.append(str(path))
                return tool_input.get("pattern"), filters


            def search_args(command: str) -> list[str] | None:
                """Find the grep-family arguments of the first command in a pipeline or chain.

                Returns:
                    The arguments after the search tool, or None when it is not a search.
                """
                segment = SEGMENT_SPLIT_RE.split(command, maxsplit=1)[0]
                try:
                    argv = shlex.split(segment)
                except ValueError:
                    return None
                if argv and argv[0] in SEARCH_TOOLS:
                    return argv[1:]
                if argv[:2] == ["git", "grep"]:
                    return argv[2:]
                return None


            def classify_args(args: list[str]) -> tuple[list[str], list[str], list[str]]:
                """Sort search arguments into regexp values, filter values and positionals.

                Returns:
                    The -e/--regexp values, the file-filter values and the positionals.
                """
                regexps: list[str] = []
                filters: list[str] = []
                positionals: list[str] = []
                expect: str | None = None
                for arg in args:
                    name, _, value = arg.partition("=") if arg.startswith("--") else (arg, "", "")
                    if expect is not None:
                        name, value, expect = expect, arg, None
                    elif arg in VALUE_OPTS:
                        expect = arg
                        continue
                    elif arg == "--" or (arg.startswith("-") and arg != "-" and not value):
                        continue
                    elif not arg.startswith("-"):
                        positionals.append(arg)
                        continue
                    if name in FILTER_OPTS:
                        filters.append(value)
                    elif name in REGEXP_OPTS:
                        regexps.append(value)
                return regexps, filters, positionals


            def from_command(command: str) -> tuple[str | None, list[str]]:
                """Read a shell grep-family command.

                Returns:
                    The pattern and the file filters, or (None, []) when not a search.
                """
                args = search_args(command)
                if args is None:
                    return None, []
                regexps, filters, positionals = classify_args(args)
                pattern = regexps[0] if regexps else (positionals.pop(0) if positionals else None)
                filters.extend(f for p in positionals if (f := file_filter(p)))
                return pattern, filters


            def seen_file(session_id: str) -> Path:
                """Locate the temp file holding the symbols blocked in a session.

                Returns:
                    A path in the system temp directory keyed by session id.
                """
                safe = re.sub(r"[^A-Za-z0-9_-]", "_", session_id) or "unknown"
                return Path(tempfile.gettempdir()) / f"claude-prefer-lsp-{safe}.json"


            def already_blocked(path: Path, symbol: str) -> bool:
                """Record a blocked symbol.

                Returns:
                    True when the symbol was blocked earlier in the session.
                """
                try:
                    seen = set(json.loads(path.read_text(encoding="utf-8")))
                except (OSError, ValueError, TypeError):
                    seen = set()
                if symbol in seen:
                    return True
                seen.add(symbol)
                with contextlib.suppress(OSError):
                    path.write_text(json.dumps(sorted(seen)), encoding="utf-8")
                return False


            def deny(symbol: str) -> None:
                """Write the PreToolUse deny decision for a symbol search."""
                reason = (
                    f"'{symbol}' looks like a Python symbol. Use the LSP tool (ty) instead of "
                    "text search: it can search the workspace for a symbol by name, jump to "
                    "its definition, find all references and trace callers. If you need a "
                    "text search anyway, repeat the same search and it will run."
                )
                decision = {
                    "hookSpecificOutput": {
                        "hookEventName": "PreToolUse",
                        "permissionDecision": "deny",
                        "permissionDecisionReason": reason,
                    }
                }
                sys.stdout.write(json.dumps(decision) + "\\n")


            def main() -> None:
                try:
                    payload = json.load(sys.stdin)
                except (json.JSONDecodeError, OSError):
                    sys.exit(0)
                if not isinstance(payload, dict):
                    sys.exit(0)
                tool_name = payload.get("tool_name")
                tool_input = payload.get("tool_input") or {}
                if tool_name == "Grep":
                    pattern, filters = from_grep_tool(tool_input)
                elif tool_name in {"Bash", "PowerShell"}:
                    pattern, filters = from_command(str(tool_input.get("command", "")))
                else:
                    sys.exit(0)
                symbol = symbol_of(pattern)
                if symbol is None or not covers_python(filters):
                    sys.exit(0)
                if already_blocked(seen_file(str(payload.get("session_id", ""))), symbol):
                    sys.exit(0)
                deny(symbol)
                sys.exit(0)


            if __name__ == "__main__":
                main()
        '''
    )
