def classify_instruction_rules(project_root: Path) -> list[ClassifiedRule]:
    """Read and classify all instruction files by audience.

    Args:
        project_root: Project root directory.

    Returns:
        List of classified rules.

    """
    instructions_dir = project_root / ".github" / "instructions"
    if not instructions_dir.exists():
        return []

    rules: list[ClassifiedRule] = []
    for src_file in sorted(instructions_dir.iterdir()):
        if not src_file.name.endswith(".instructions.md"):
            continue

        content = src_file.read_text(encoding="utf-8")
        fm = _parse_instruction_frontmatter(content)

        exclude = fm.get("excludeAgent", "")
        if exclude in ("coding-agent", "all"):
            continue

        apply_to = fm.get("applyTo", "")
        if not apply_to:
            continue

        audience = fm.get("audience", "shared")
        body = _extract_body_after_frontmatter(content)

        patterns = _convert_apply_to_paths(apply_to)
        is_global = all(_is_global_pattern(p) for p in patterns)

        subtree_prefixes: list[str] = []
        if not is_global:
            for p in patterns:
                prefix = _extract_subtree_prefix(p)
                if prefix is None or _is_vendor_mirror_prefix(prefix):
                    continue
                if prefix not in subtree_prefixes:
                    subtree_prefixes.append(prefix)

        rules.append(
            ClassifiedRule(
                filename=src_file.name,
                audience=audience,
                apply_to=apply_to,
                body=body,
                is_global=is_global,
                subtree_prefixes=subtree_prefixes,
            )
        )

    return rules


def sync_claude_rules(project_root: Path, config: GzkitConfig | None = None) -> list[str]:
    """Mirror .github/instructions/*.instructions.md to .claude/rules/*.md.

    Uses config.paths.claude_rules instead of hardcoded path.

    Args:
        project_root: Project root directory.
        config: Optional project configuration.

    Returns:
        List of mirrored file paths (relative to project_root).

    """
    if config is None:
        config = GzkitConfig.load(project_root / ".gzkit.json")

    instructions_dir = project_root / ".github" / "instructions"
    rules_dir = project_root / config.paths.claude_rules
    ensure_dir(rules_dir)

    updated: list[str] = []
    expected_names: set[str] = set()

    if instructions_dir.exists():
        for src_file in sorted(instructions_dir.iterdir()):
            if not src_file.name.endswith(".instructions.md"):
                continue

            content = src_file.read_text(encoding="utf-8")
            fm = _parse_instruction_frontmatter(content)

            exclude = fm.get("excludeAgent", "")
            if exclude in ("coding-agent", "all"):
                continue

            apply_to = fm.get("applyTo", "")
            if not apply_to:
                _logger.warning("Skipping %s: no applyTo frontmatter.", src_file.name)
                continue

            body = _extract_body_after_frontmatter(content)
            target_name = src_file.name.replace(".instructions.md", ".md")
            expected_names.add(target_name)

            if apply_to.strip() == "**/*":
                output = body.lstrip("\n")
            else:
                paths = _convert_apply_to_paths(apply_to)
                paths_yaml = "\n".join(f'  - "{p}"' for p in paths)
                output = f"---\npaths:\n{paths_yaml}\n---\n{body}"

            target = rules_dir / target_name
            write_text_if_changed(target, output)
            updated.append(target.relative_to(project_root).as_posix())

    if rules_dir.exists():
        for existing in rules_dir.iterdir():
            if existing.is_file() and existing.name not in expected_names:
                remove_if_present(existing)

    return updated


def _classify_canonical_rules(project_root: Path) -> list[ClassifiedRule]:
    """Classify rules straight from ``.gzkit/rules/`` canon.

    Equivalent to :func:`classify_instruction_rules` BY CONSTRUCTION, not by
    resemblance: ``apply_to`` is built the same way
    :func:`render_rule_for_copilot` builds it, and the same
    ``_convert_apply_to_paths`` / ``_is_global_pattern`` /
    ``_extract_subtree_prefix`` helpers do the rest. The copilot rendering emits
    only ``applyTo``, so ``audience`` and ``excludeAgent`` are already absent
    from every canon-rendered instruction file and their defaults here lose
    nothing.
    """
    canonical_dir = project_root / ".gzkit" / "rules"
    if not canonical_dir.is_dir():
        return []
    classified: list[ClassifiedRule] = []
    for rule in load_rules(canonical_dir):
        apply_to = ", ".join(rule.frontmatter.paths)
        patterns = _convert_apply_to_paths(apply_to)
        is_global = all(_is_global_pattern(p) for p in patterns)
        subtree_prefixes: list[str] = []
        if not is_global:
            for pattern in patterns:
                prefix = _extract_subtree_prefix(pattern)
                if prefix is None or _is_vendor_mirror_prefix(prefix):
                    continue
                if prefix not in subtree_prefixes:
                    subtree_prefixes.append(prefix)
        classified.append(
            ClassifiedRule(
                filename=f"{rule.frontmatter.id.replace('-', '_')}.instructions.md",
                audience="shared",
                apply_to=apply_to,
                # `_RENDER_HEADER` prefix, exactly as `render_rule_for_copilot`
                # emits it: the body that reached this classifier used to be the
                # RENDERED file's, header included, and nested `AGENTS.md`
                # embedded that header per section. Dropping it would be a
                # cosmetic improvement and a 92-line churn across 29 generated
                # surfaces, which is not this GHI's business. Byte-identical
                # output keeps the equivalence claim exact rather than
                # "equivalent apart from a marker".
                body=f"{_RENDER_HEADER}\n{rule.body}",
                is_global=is_global,
                subtree_prefixes=subtree_prefixes,
            )
        )
    return classified


def _shared_subtree_rules(project_root: Path) -> dict[str, list[ClassifiedRule]]:
    """Group shared, non-global rules by the subtree each one applies to.

    Canon first (GHI #891). This used to read ONLY ``.github/instructions/`` --
    a GENERATED surface -- to decide what to generate, held together by an
    ordering comment in ``sync_all`` asking the caller to render Copilot rules
    first. A derived view feeding a derived view is what ``AGENTS.md``
    § Architectural Boundaries #6 forbids, and it made ``sync_all``
    unable to render without first writing: under a capture sink the instruction
    files are not on disk, classification came back empty, and all 14 nested
    ``AGENTS.md`` silently vanished from the plan.

    The instruction-file path remains as the fallback for trees with no
    ``.gzkit/rules/`` canon -- an adopter hand-authoring ``.github/instructions/``
    directly -- where those files ARE the source rather than a rendering of one.
    """
    canonical = _classify_canonical_rules(project_root)
    rules = canonical if canonical else classify_instruction_rules(project_root)
    subtree_rules: dict[str, list[ClassifiedRule]] = {}
    for rule in rules:
        if rule.audience != "shared" or rule.is_global:
            continue
        for prefix in rule.subtree_prefixes:
            subtree_rules.setdefault(prefix, []).append(rule)
    return subtree_rules


_CLAUDE_REDIRECT_BODY = (
    f"{_GENERATED_MARKER}\n"
    "# {subtree} Agent Instructions (Claude)\n\n"
    "> Claude discovers nested instruction files as `CLAUDE.md`; the shared\n"
    "> subtree rules live in the sibling `AGENTS.md`. This file imports them so\n"
    "> either harness reads the same governance surface (GHI #923).\n\n"
    "@AGENTS.md\n"
)


def _subtree_sections(rules_for_subtree: list[ClassifiedRule]) -> list[str]:
    """Rule bodies that will render into a subtree's ``AGENTS.md``.

    One predicate for "does this subtree get a file", shared by the writer and
    by :func:`nested_agents_md_paths`. Two copies would drift on the
    empty-body case, and the helper under-reporting the writer is the class of
    defect GHI #890 closed.
    """
    return [body for rule in rules_for_subtree if (body := rule.body.strip())]


def _foreign_vendor_roots(project_root: Path, config: GzkitConfig) -> tuple[Path, ...]:
    """Surface roots belonging to a vendor other than Claude.

    A Claude redirect is not written inside one: those trees carry their own
    vendor's discovery convention, and seeding another vendor's root with
    ``CLAUDE.md`` claims a surface gzkit does not own there. Derived from the
    declared vendor set rather than a literal list, so retiring a vendor
    removes its root here in the same edit.
    """
    vendors = config.vendors
    return tuple(
        project_root / vendor.surface_root
        for name in type(vendors).model_fields
        if name != "claude" and (vendor := getattr(vendors, name)).surface_root
    )


def _within_any(path: Path, roots: tuple[Path, ...]) -> bool:
    """Whether *path* is one of *roots* or nested beneath one."""
    return any(path == root or root in path.parents for root in roots)


def _nested_subtrees(project_root: Path) -> list[tuple[str, Path, list[str]]]:
    """``(subtree, subtree_dir, sections)`` for every subtree that gets a file.

    The single walk both :func:`sync_nested_agents_md` and
    :func:`nested_agents_md_paths` read, so the write set and the writer cannot
    disagree about which directories are in play.
    """
    found: list[tuple[str, Path, list[str]]] = []
    for subtree, rules_for_subtree in sorted(_shared_subtree_rules(project_root).items()):
        subtree_dir = project_root / subtree
        # `dir_exists`, not `is_dir`: inside a captured sync the directory an
        # earlier pass would create is not on disk yet, and `is_dir` would answer
        # about the PRE-sync tree -- silently dropping `.gzkit/skills/AGENTS.md`
        # from the plan (GHI #891).
        if dir_exists(subtree_dir):
            found.append((subtree, subtree_dir, _subtree_sections(rules_for_subtree)))
    return found


def nested_agents_md_paths(project_root: Path, config: GzkitConfig | None = None) -> set[Path]:
    """Every nested path :func:`sync_nested_agents_md` may write.

    Covers both surfaces it emits: the subtree ``AGENTS.md`` and the sibling
    ``CLAUDE.md`` redirect (GHI #923). Derived from the same walk the writer
    uses, so a caller that must know the write set cannot fall out of step with
    it. Callers that snapshot before a sync (``validate_pkg.sync_parity``) need
    exactly this set: a hand-maintained list is what let ``gz validate
    --surfaces`` leave 16 files modified after a read-only run — the tuple named
    3 paths while the writer touched ~19, so restore could only put back the 3
    it knew about.
    """
    if config is None:
        config = GzkitConfig.load(project_root / ".gzkit.json")
    foreign = _foreign_vendor_roots(project_root, config)
    paths: set[Path] = set()
    for _subtree, subtree_dir, sections in _nested_subtrees(project_root):
        paths.add(subtree_dir / "AGENTS.md")
        if sections and not _within_any(subtree_dir, foreign):
            paths.add(subtree_dir / "CLAUDE.md")
    return paths


def sync_nested_agents_md(project_root: Path, config: GzkitConfig | None = None) -> list[str]:
    """Generate nested AGENTS.md files for shared subtree rules.

    Args:
        project_root: Project root directory.
        config: Optional project configuration.

    Returns:
        List of nested AGENTS.md file paths (relative to project_root).

    """
    if config is None:
        config = GzkitConfig.load(project_root / ".gzkit.json")

    foreign = _foreign_vendor_roots(project_root, config)

    updated: list[str] = []
    expected_paths: set[Path] = set()
    expected_redirects: set[Path] = set()

    # `_nested_subtrees` carries the `dir_exists` guard that `nested_agents_md_paths`
    # also reads. The two MUST ask the same question: the helper exists so a caller
    # can know this writer's write set, and a guard that differs by even one
    # predicate reintroduces the drift GHI #890 closed. Under a capture sink an
    # earlier pass's directory is recorded rather than created, so a bare `is_dir`
    # dropped `src/AGENTS.md` from the plan while apply mode still wrote it.
    for subtree, subtree_dir, sections in _nested_subtrees(project_root):
        agents_path = subtree_dir / "AGENTS.md"
        expected_paths.add(agents_path)

        if not sections:
            continue

        content = (
            f"{_GENERATED_MARKER}\n"
            f"# {subtree} Agent Instructions\n\n"
            "> Shared subtree rules. See root `AGENTS.md` for project-wide governance.\n\n"
            + "\n\n".join(sections)
            + "\n"
        )

        write_text_if_changed(agents_path, content)
        updated.append(agents_path.relative_to(project_root).as_posix())

        # Claude discovers nested instruction files as CLAUDE.md, so the subtree
        # rules above reach Codex alone without this redirect (GHI #923). An
        # import rather than a copy: two renderings of one rule set can disagree
        # after a later sync, and the root surface already establishes the
        # pattern (`CLAUDE.md` -> `@AGENTS.md`, GHI #525).
        if _within_any(subtree_dir, foreign):
            continue
        redirect_path = subtree_dir / "CLAUDE.md"
        expected_redirects.add(redirect_path)
        write_text_if_changed(redirect_path, _CLAUDE_REDIRECT_BODY.format(subtree=subtree))
        updated.append(redirect_path.relative_to(project_root).as_posix())

    mirror_roots = _mirror_owned_roots(project_root, config)
    _cleanup_stale_nested_agents(project_root, expected_paths, mirror_roots)
    _cleanup_stale_nested_agents(
        project_root, expected_redirects, mirror_roots, filename="CLAUDE.md"
    )

    return updated


def _mirror_owned_roots(project_root: Path, config: GzkitConfig) -> tuple[tuple[Path, Path], ...]:
    """``(mirror_root, canonical_root)`` pairs whose ``AGENTS.md`` files are copies.

    ``sync_skill_mirror`` copies the canonical skills tree into each vendor
    path, and ``sync_pkg_surfaces`` copies it into the wheel-shipping package
    tree. The canonical root travels with each mirror because a copy is only
    stale when its SOURCE is gone -- excluding mirror trees outright would keep
    them from churning but would also orphan a copy forever once the canonical
    file it mirrors is retired, and ``sync_skill_mirror`` is documented as
    "intentionally additive/non-destructive", so nothing else would remove it.
    """
    canonical = project_root / config.paths.skills
    mirrors = (
        config.paths.claude_skills,
        config.paths.copilot_skills,
        config.paths.codex_skills,
        "src/gzkit/skills",
    )
    pairs = {
        (project_root / rel, canonical)
        for rel in mirrors
        if rel and project_root / rel != canonical
    }
    return tuple(sorted(pairs))


def _mirror_root_for(
    agents_file: Path, mirror_roots: tuple[tuple[Path, Path], ...]
) -> tuple[Path, Path] | None:
    """Return the ``(mirror_root, canonical_root)`` pair owning ``agents_file``."""
    for pair in mirror_roots:
        if agents_file.is_relative_to(pair[0]):
            return pair
    return None


def _cleanup_stale_nested_agents(
    project_root: Path,
    expected_paths: set[Path],
    mirror_roots: tuple[tuple[Path, Path], ...] = (),
    filename: str = "AGENTS.md",
) -> None:
    """Remove nested *filename* files not in the expected set.

    ``filename`` selects the surface swept -- ``AGENTS.md`` for the subtree
    rules themselves, ``CLAUDE.md`` for the Claude redirects beside them
    (GHI #923). One sweep serves both because the mirror-exclusion policy below
    is a property of the TREE, not of the name: a redirect copied into
    ``.claude/skills/`` by the mirror pass is exactly as marker-bearing and
    exactly as absent from ``expected_paths`` as a copied ``AGENTS.md``, so a
    second sweep written without this policy would re-open the GHI #890 churn
    under the new name.

    Only deletes files bearing the gzkit generated marker, and never removes a
    mirror copy whose canonical source survives -- those trees belong to the
    skill and package mirror writers.

    The exclusion is load-bearing rather than defensive. A canonical nested
    ``AGENTS.md`` carries the generated marker, so every mirror copy of it
    carries the marker too while never appearing in ``expected_paths``.
    Scanning the whole project therefore deleted six mirrored files on each
    sync -- ``.claude/skills/``, ``.agents/skills/``, ``.github/skills/`` --
    which the mirror pass re-created moments later. The final tree looks
    untouched, so neither ``git status`` nor a bytes comparison shows it; what
    it actually does is briefly remove a governance surface and rewrite it on
    every run (GHI #890).

    Deletion is decided for the whole sweep before any file is unlinked.
    Deciding as it walks makes the outcome depend on ``rglob`` order: a
    canonical file and its mirror are both marker-bearing, so visiting the
    canonical first deletes it and leaves the mirror looking like an orphan,
    while visiting the mirror first spares it. Same tree, two results.
    """
    root_agents = project_root / filename
    candidates = [
        path
        for path in project_root.rglob(filename)
        if path != root_agents and path not in expected_paths
    ]
    surviving_canonicals = {path for path in candidates if not _mirror_root_for(path, mirror_roots)}
    for agents_file in candidates:
        pair = _mirror_root_for(agents_file, mirror_roots)
        if pair is not None:
            mirror_root, canonical_root = pair
            counterpart = canonical_root / agents_file.relative_to(mirror_root)
            # A copy is stale only when its source is gone -- either absent now,
            # or slated for removal by this same sweep.
            if counterpart.is_file() and counterpart not in surviving_canonicals:
                continue
        try:
            first_line = agents_file.read_text(encoding="utf-8").split("\n", 1)[0]
            if "Generated by gzkit" in first_line:
                remove_if_present(agents_file)
        except (OSError, UnicodeDecodeError):
            pass


def validate_rule_placement(project_root: Path) -> list[str]:
    """Check for misplaced rules.

    Args:
        project_root: Project root directory.

    Returns:
        List of warning messages.

    """
    warnings: list[str] = []
    rules = classify_instruction_rules(project_root)

    claude_rules_dir = project_root / ".claude" / "rules"

    for rule in rules:
        if rule.audience == "claude-only":
            target_name = rule.filename.replace(".instructions.md", ".md")
            if not (claude_rules_dir / target_name).exists():
                warnings.append(
                    f"{rule.filename}: audience is claude-only but not mirrored to .claude/rules/"
                )
        elif rule.audience == "shared" and not rule.is_global:
            for prefix in rule.subtree_prefixes:
                subtree_dir = project_root / prefix
                agents_path = subtree_dir / "AGENTS.md"
                if subtree_dir.exists() and not agents_path.exists():
                    warnings.append(
                        f"{rule.filename}: shared subtree rule for '{prefix}' "
                        f"has no nested AGENTS.md"
                    )

    return warnings


