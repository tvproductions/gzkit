_logger = logging.getLogger(__name__)

_GENERATED_MARKER = "<!-- Generated by gzkit — do not edit manually -->"

#: Generated per-subtree surfaces, which are NOT rule files even when they sit in
#: the canonical rules directory. Three scanners each skipped ``AGENTS.md`` by
#: literal name -- ``load_rules``, ``validators.rule_version_markers`` and
#: ``validators.unscoped_rules``. Each literal was a one-member allowlist for a
#: family, so adding the Claude redirect beside it (GHI #923) made
#: `.gzkit/rules/CLAUDE.md` a rule file to all three at once: a missing
#: frontmatter delimiter, a missing rule-version marker, and a missing `paths:`
#: scope. Public and shared so a fourth generated surface cannot reopen this
#: three ways.
NESTED_SURFACE_NAMES: frozenset[str] = frozenset({"AGENTS.md", "CLAUDE.md"})


def _classify_rule_file(
    path: Path,
    *,
    project_root: Path | None = None,
) -> Literal["canonical", "package_only", "runtime_state"]:
    """Classify a rules-surface file into one of three content classes.

    canonical: *.md rule files, plus any non-Python/non-markdown asset that has
               a counterpart at ``.gzkit/rules/<rel>`` (e.g. JSON sidecars
               authored on the canonical side).
    package_only: ``__init__.py``, ``__pycache__/**``, Python modules with no
                  ``.gzkit/rules/`` counterpart (e.g. ``_scaffolder.py``), and
                  non-markdown assets without a canonical counterpart.
    runtime_state: (currently unused for the rules surface; reserved for
                   parity with ``_classify_chore_file``.)

    Signature-compatible with :func:`gzkit.chores._classify_chore_file`. See
    ``.gzkit/rules/skill-surface-sync.md`` § class-classifier.
    """
    path = Path(path)
    name = path.name
    parts = path.parts
    path_posix = path.as_posix()

    # package_only: __init__.py and __pycache__
    if name == "__init__.py" or "__pycache__" in parts:
        return "package_only"

    # Already under .gzkit/rules/ -> canonical (authored side)
    if ".gzkit/rules/" in path_posix:
        return "canonical"

    # Markdown rule files are canonical by default.
    if name.endswith(".md"):
        return "canonical"

    # For Python modules and non-markdown assets under src/gzkit/rules/,
    # resolve a counterpart at .gzkit/rules/<rel> when project_root is known.
    if project_root is not None:
        try:
            rel = path.relative_to(project_root / "src" / "gzkit" / "rules")
        except ValueError:
            rel = None
        if rel is not None:
            counterpart = project_root / ".gzkit" / "rules" / rel
            return "canonical" if counterpart.exists() else "package_only"

    # Fallback when project_root is not provided: resolve relative to CWD
    # when the path lives under src/gzkit/rules/.
    if "src/gzkit/rules/" in path_posix:
        cwd_root = Path.cwd()
        try:
            rel = path.relative_to(cwd_root / "src" / "gzkit" / "rules")
        except ValueError:
            # Try interpreting the input as repo-relative (e.g. when the
            # caller passes a path like Path("src/gzkit/rules/foo.json")
            # without an absolute root).
            try:
                rel = path.relative_to(Path("src/gzkit/rules"))
            except ValueError:
                rel = None
        if rel is not None:
            counterpart = cwd_root / ".gzkit" / "rules" / rel
            return "canonical" if counterpart.exists() else "package_only"

    return "package_only"


class ClassifiedRule(BaseModel):
    """An instruction rule with audience classification."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    filename: str = Field(..., description="Source instruction filename")
    audience: str = Field("shared", description="shared or claude-only")
    apply_to: str = Field(..., description="Raw applyTo frontmatter value")
    body: str = Field(..., description="Rule body content after frontmatter")
    is_global: bool = Field(..., description="Whether the rule applies globally")
    subtree_prefixes: list[str] = Field(
        default_factory=list, description="Directory prefixes for subtree rules"
    )


